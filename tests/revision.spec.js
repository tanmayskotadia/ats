import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

const original = 'Alex Rivera\nalex@example.com\nExperience\nAnalyst | Acme\nJan 2020 - Dec 2022\n• Helped with monthly business reports.\nSkills\nSQL, Tableau';
const file = (name, text) => ({ name, mimeType: 'text/plain', buffer: Buffer.from(text) });

test('corrects text, updates job matching, exports the revision, and restores the original', async ({ page }) => {
  const cloud = [];
  await page.route('**/api/status', route => route.fulfill({ json: { aiEnabled: true } }));
  await page.route('**/api/analyze', route => { cloud.push(route.request().postData()); return route.abort(); });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.locator('#use-ml').uncheck();
  await page.locator('#job-panel summary').click();
  await page.locator('#job').fill('Required skills: Python, SQL');
  await page.locator('#file').setInputFiles(file('resume.txt', original));
  await page.locator('#scan').click();
  await expect(page.getByRole('heading', { name: 'Edits to work on' })).toBeVisible();
  const score = Number(await page.locator('.report-banner .ring strong').textContent());
  await page.getByRole('button', { name: 'Edit text and rescan' }).click();
  await expect(page.locator('#edit-ai')).not.toBeChecked();
  await page.locator('#edit-text').fill('Draft to discard');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Edit text and rescan' }).click();
  await expect(page.locator('#edit-text')).toHaveValue(original);
  await page.locator('#edit-text').fill('bad');
  await page.getByRole('button', { name: 'Update report' }).click();
  await expect(page.locator('#edit-error')).toContainText('readable resume text');
  expect(Number(await page.locator('.report-banner .ring strong').textContent())).toBe(score);
  const edited = original.replace('SQL, Tableau', 'SQL, Tableau, Python');
  await page.locator('#edit-text').fill(edited);
  await page.getByRole('button', { name: 'Update report' }).click();
  await expect(page.locator('#edit-dialog')).not.toBeVisible();
  await expect(page.locator('.revision-note')).toContainText('Previous score ' + score + '/100');
  expect(Number(await page.locator('.report-banner .ring strong').textContent())).toBeGreaterThan(score);
  await page.getByRole('tab', { name: 'Parsed resume' }).click();
  await expect(page.locator('pre')).toHaveText(edited);
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Profile JSON' }).click();
  const download = await pending;
  const profile = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(profile.revision).toBe(1);
  expect(profile.textSource).toBe('edited');
  expect(profile.analyzedText).toBe(edited);
  expect(profile.score.keywords.matched.map(item => item.label)).toContain('Python');
  expect(profile.feedback.some(item => item.evidence.includes('Helped'))).toBe(true);
  await page.getByRole('button', { name: 'Edit text and rescan' }).click();
  await page.getByRole('button', { name: 'Restore extracted text' }).click();
  await expect(page.locator('#edit-text')).toHaveValue(original);
  await page.locator('#edit-job').fill('Required skills: Tableau');
  await page.getByRole('button', { name: 'Update report' }).click();
  await expect(page.locator('.revision-note')).toContainText('Job description changed');
  await expect(page.locator('.revision-note')).toContainText('original extracted text');
  expect(cloud).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth)).toBe(true);
});

test('editing one batch report preserves the other completed report and updates the CSV', async ({ page }) => {
  await page.goto('/');
  await page.locator('#use-ml').uncheck();
  await page.locator('#file').setInputFiles([file('one.txt', original), file('two.txt', original.replace('Alex Rivera', 'Jordan Miller'))]);
  await page.getByRole('button', { name: 'Analyze 2 resumes' }).click();
  await expect(page.getByText('2 of 2 finished')).toBeVisible();
  await page.getByRole('button', { name: 'Open report' }).first().click();
  await page.getByRole('button', { name: 'Edit text and rescan' }).click();
  await page.locator('#edit-text').fill(original.replace('Alex Rivera', 'Alex Updated'));
  await page.getByRole('button', { name: 'Update report' }).click();
  await expect(page.getByRole('heading', { name: 'Alex Updated', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to batch' }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export batch summary' }).click();
  const csv = await readFile(await (await pending).path(), 'utf8');
  expect(csv).toContain('Edited text');
  expect(csv).toContain('File extraction');
  await page.getByRole('button', { name: 'Open report' }).last().click();
  await expect(page.getByRole('heading', { name: 'Jordan Miller', exact: true })).toBeVisible();
  await expect(page.locator('.revision-note')).toHaveCount(0);
});
